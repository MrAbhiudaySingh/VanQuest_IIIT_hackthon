import { ASSETS, TRADE_FEE } from '../data/market.js';
import { price, history, portfolio, quoteTrade, trade } from '../sim/market.js';
import { balance, transfer } from '../sim/ledger.js';
import { inr, fmtShortDate } from '../sim/util.js';
import { esc, newToken, why as whyBase } from './core.js';

const why = r => r?.reason === 'insufficient_funds' ? 'Not enough investment cash — move money in from your wallet below.' : whyBase(r);

const pct = x => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(1)}%`;
const cls = x => (x > 0 ? 'pos' : x < 0 ? 'neg' : '');

function spark(values, w = 90, h = 26) {
  const lo = Math.min(...values), hi = Math.max(...values), span = hi - lo || 1;
  const pts = values.map((v, i) => `${(i / (values.length - 1)) * w},${h - 2 - ((v - lo) / span) * (h - 4)}`).join(' ');
  const up = values.at(-1) >= values[0];
  return `<svg class="spark" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" aria-hidden="true"><polyline fill="none" stroke="${up ? '#5fd68a' : '#ff7a7a'}" stroke-width="1.5" points="${pts}"/></svg>`;
}

export class TradingPanel {
  constructor(game) {
    this.game = game;
    this.title = 'Summit Practice Trading Desk';
    this.sub = 'Simulated market for learning — fictional assets, not real or live prices';
    this.tab = 'market';
    this.sel = 'SAGAR50'; this.side = 'buy'; this.qty = 1; this.move = 1000;
    this.confirm = null; this.msg = null;
  }
  get s() { return this.game.state; }

  headExtra() {
    return `<div class="tabs" style="margin:0">${[['market', 'Market'], ['portfolio', 'Portfolio'], ['history', 'History'], ['learn', 'Risk guide']]
      .map(([t, l]) => `<button class="tab ${this.tab === t ? 'on' : ''}" data-a="tab" data-t="${t}">${l}</button>`).join('')}</div>`;
  }

  render() {
    const p = portfolio(this.s);
    const kpis = `<div class="kpis">
      <div class="kpi"><div class="k">Investment cash</div><div class="v">${inr(p.cash)}</div></div>
      <div class="kpi"><div class="k">Holdings value</div><div class="v">${inr(p.invested)}</div></div>
      <div class="kpi"><div class="k">Portfolio total</div><div class="v">${inr(p.total)}</div></div>
      <div class="kpi"><div class="k">Unrealised P/L</div><div class="v ${cls(p.unrealized)}">${inr(p.unrealized)}</div></div>
      <div class="kpi"><div class="k">Realised P/L</div><div class="v ${cls(p.realized)}">${inr(p.realized)}</div></div></div>`;
    const banner = `<div class="row" style="margin-bottom:10px"><span class="sim-banner">SIMULATION</span><span class="muted">Educational practice market. Prices are generated by the game and change as in-game days pass. No real trades, money or brokers.</span></div>`;
    const msg = this.msg ? `<div class="msg ${this.msg.kind}">${esc(this.msg.text)}</div>` : '';
    return banner + kpis + msg + this[`render_${this.tab}`](p);
  }

  render_market() {
    const rows = Object.entries(ASSETS).map(([id, a]) => {
      const px = price(this.s, id), d1 = px / price(this.s, id, Math.max(0, this.s.day - 1)) - 1, d30 = px / price(this.s, id, Math.max(0, this.s.day - 30)) - 1;
      return `<tr class="${this.sel === id ? 'sel' : ''}"><td><b>${esc(a.name)}</b><div class="muted">${id} · ${esc(a.type)} · risk ${esc(a.risk)}</div></td>
        <td class="n">${inr(px)}</td><td class="n ${cls(d1)}">${pct(d1)}</td><td class="n ${cls(d30)}">${pct(d30)}</td><td>${spark(history(this.s, id, 30))}</td>
        <td><button class="btn sm" data-a="pick" data-id="${id}">Trade</button></td></tr>`;
    }).join('');
    return `<div class="split"><div><table class="t"><tr><th>Asset (simulated)</th><th class="n">Price</th><th class="n">1 day</th><th class="n">30 days</th><th>30-day trend</th><th></th></tr>${rows}</table></div>
      <div>${this.renderTicket()}${this.renderTransfer()}</div></div>`;
  }

  renderTicket() {
    const a = ASSETS[this.sel], q = quoteTrade(this.s, this.sel, this.side, this.qty);
    const held = this.s.brokerage.holdings[this.sel]?.qty ?? 0;
    const conf = this.confirm ? `<div class="confirm"><h4>Confirm ${this.side}</h4>
        <p>${this.side === 'buy' ? 'Buy' : 'Sell'} <b>${this.qty}</b> × ${esc(a.name)} at ${inr(q.price)}<br>Value ${inr(q.gross)} ${this.side === 'buy' ? '+' : '−'} ${inr(TRADE_FEE)} fee = <b>${inr(q.net)}</b> ${this.side === 'buy' ? 'paid from' : 'added to'} investment cash.</p>
        <div class="row"><button class="btn primary" data-a="trade-confirm">Confirm</button><button class="btn" data-a="cancel">Cancel</button></div></div>` : '';
    return `<div class="card"><h3>${esc(a.name)} <span class="tag">${this.sel}</span></h3><div class="muted">${esc(a.about)}</div>
      <div class="row"><button class="tab ${this.side === 'buy' ? 'on' : ''}" data-a="side" data-t="buy">Buy</button><button class="tab ${this.side === 'sell' ? 'on' : ''}" data-a="side" data-t="sell">Sell</button>
        <span class="muted">You hold ${held}</span></div>
      <label class="row">Quantity <input class="num" type="number" min="1" step="1" value="${this.qty}" data-in="qty"></label>
      <div class="muted">${q.ok ? `Estimated ${this.side === 'buy' ? 'cost' : 'proceeds'}: <b>${inr(q.net)}</b> (incl. ${inr(TRADE_FEE)} fee)` : `<span class="neg">${esc(why(q))}</span>`}</div>
      <button class="btn primary" data-a="review" ${q.ok && !this.confirm ? '' : 'disabled'}>Review ${this.side}</button>${conf}</div>`;
  }

  renderTransfer() {
    return `<div class="card" style="margin-top:8px"><h3>Move money</h3>
      <div class="muted">Wallet ${inr(balance(this.s))} ⇄ Investment cash ${inr(balance(this.s, 'brokerage'))}</div>
      <div class="row"><input class="num" type="number" min="1" step="100" value="${this.move}" data-in="move" aria-label="amount">
        <button class="btn sm" data-a="deposit">Wallet → Invest</button><button class="btn sm" data-a="withdraw">Invest → Wallet</button></div></div>`;
  }

  render_portfolio(p) {
    if (!p.rows.length) return '<div class="empty">No holdings yet. Move money into investment cash, then buy from the Market tab.</div>';
    const rows = p.rows.map(r => `<tr><td><b>${esc(ASSETS[r.id].name)}</b><div class="muted">${r.id}</div></td><td class="n">${r.qty}</td>
      <td class="n">${inr(r.cost / r.qty)}</td><td class="n">${inr(r.price)}</td><td class="n">${inr(r.cost)}</td><td class="n">${inr(r.value)}</td>
      <td class="n ${cls(r.pnl)}">${inr(r.pnl)} (${pct(r.pnlPct)})</td><td class="n">${p.invested ? Math.round(r.value / p.invested * 100) : 0}%</td></tr>`).join('');
    const top = Math.max(...p.rows.map(r => r.value)) / (p.invested || 1);
    return `<table class="t"><tr><th>Asset</th><th class="n">Units</th><th class="n">Avg cost</th><th class="n">Price</th><th class="n">Cost basis</th><th class="n">Value</th><th class="n">P/L</th><th class="n">Weight</th></tr>${rows}</table>
      <div class="msg ${top > 0.6 ? 'warn' : 'ok'}" style="margin-top:10px">Diversification: ${p.rows.length} holding(s); largest is ${Math.round(top * 100)}% of your investments.
      ${top > 0.6 ? 'Most of your money rides on one asset — a single bad event would hurt a lot.' : 'No single asset dominates.'}</div>
      <p class="muted">Cost basis includes the ${inr(TRADE_FEE)} fee per buy. Selling uses the average-cost method.</p>`;
  }

  render_history() {
    const t = [...this.s.brokerage.trades].reverse();
    if (!t.length) return '<div class="empty">No trades yet.</div>';
    return `<table class="t"><tr><th>Date</th><th>Trade</th><th class="n">Price</th><th class="n">Fee</th><th class="n">Cash</th><th class="n">Realised P/L</th></tr>${t.map(x => `
      <tr><td>${fmtShortDate(x.day)}</td><td>${x.side === 'buy' ? 'Buy' : 'Sell'} ${x.qty} ${x.asset}</td><td class="n">${inr(x.price)}</td><td class="n">${inr(x.fee)}</td>
      <td class="n ${x.side === 'buy' ? 'neg' : 'pos'}">${x.side === 'buy' ? '−' : '+'}${inr(x.net)}</td><td class="n ${cls(x.realized ?? 0)}">${x.realized === null ? '—' : inr(x.realized)}</td></tr>`).join('')}</table>`;
  }

  render_learn() {
    return `<p><b>Risk</b> is how much an investment's value can swing — including below what you paid. Each asset here is labelled Low → Very high. Higher expected returns usually come with bigger swings.</p>
      <p><b>Diversification</b> means spreading money across different assets so one bad event can't wreck your portfolio. The Sagar 50 index fund is diversified by itself; adding the bond fund spreads risk further.</p>
      <p><b>Time horizon:</b> money you need soon (tuition, rent, emergencies) shouldn't be in volatile assets. Keep an emergency fund in your wallet first.</p>
      <p><b>Fees</b> (${inr(TRADE_FEE)} per trade here) add up when you trade often.</p>
      <p class="muted">This desk is separate from any future real-market data feature. All prices are generated by the simulation from your save's in-game date.</p>`;
  }

  onInput(el) {
    if (el.dataset.in === 'qty') { this.qty = Math.max(1, Math.floor(Number(el.value) || 1)); this.confirm = null; }
    if (el.dataset.in === 'move') this.move = Math.max(0, Math.floor(Number(el.value) || 0));
  }

  onAction(a, el) {
    this.msg = a === 'tab' ? this.msg : null;
    switch (a) {
      case 'tab': this.tab = el.dataset.t; this.confirm = null; break;
      case 'pick': this.sel = el.dataset.id; this.confirm = null; break;
      case 'side': this.side = el.dataset.t; this.confirm = null; break;
      case 'review': this.confirm = { token: newToken() }; break;
      case 'cancel': this.confirm = null; break;
      case 'trade-confirm': {
        const token = this.confirm?.token; this.confirm = null;
        const r = this.game.act(s => trade(s, this.sel, this.side, this.qty, token));
        this.msg = r.ok ? { kind: 'ok', text: `${r.trade.side === 'buy' ? 'Bought' : 'Sold'} ${r.trade.qty} ${r.trade.asset} at ${inr(r.trade.price)} (${inr(r.trade.net)} incl. fee).${r.trade.realized !== null ? ` Realised P/L ${inr(r.trade.realized)}.` : ''}` }
                        : { kind: 'error', text: why(r) };
        break;
      }
      case 'deposit': case 'withdraw': {
        const [from, to] = a === 'deposit' ? ['wallet', 'brokerage'] : ['brokerage', 'wallet'];
        const r = this.game.act(s => transfer(s, from, to, this.move, a === 'deposit' ? 'Wallet → investment cash' : 'Investment cash → wallet'));
        this.msg = r.ok ? { kind: 'ok', text: `Moved ${inr(this.move)}.` } : { kind: 'error', text: r.reason === 'insufficient_funds' ? `Not enough money in your ${from === 'wallet' ? 'wallet' : 'investment cash'}.` : whyBase(r) };
        break;
      }
    }
  }
}
