// Summit Practice Trading Desk in the supplied design (Assets/supplied-ui/round8/summit financial →
// skins/desk.css). Presentation only: prices, P/L, fees and every trade come from sim/market.js and the
// ledger, for the save's in-game date — opening or redrawing the desk never changes state. The design's
// demo script (live ticking prices, random volume, sounds) is not used: prices here move only when
// in-game days pass. The market bulletin repeats the latest monthly newspaper issue (sim/newspaper.js),
// using the local model's wording only if that issue already stored a validated version.
import { ASSETS, TRADE_FEE } from '../data/market.js';
import { price, history, portfolio, quoteTrade, trade } from '../sim/market.js';
import { balance, transfer } from '../sim/ledger.js';
import { renderIssue, monthName } from '../sim/newspaper.js';
import { ACTIVATION_ENABLED } from '../ai/proposals.js';
import { inr, fmtDate, fmtShortDate } from '../sim/util.js';
import { esc, newToken, why as whyBase } from './core.js';

const why = r => r?.reason === 'insufficient_funds' ? 'Not enough investment cash — move money in from your wallet below.' : whyBase(r);

const pct = x => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(1)}%`;
const cls = x => (x > 0 ? 'text-pos' : x < 0 ? 'text-neg' : '');
const UP = '#34d399', DOWN = '#f87171';                     // the design's trend colours

// polyline points for a series inside w×h (top/bottom padding 2)
function pts(values, w, h) {
  const lo = Math.min(...values), hi = Math.max(...values), span = hi - lo || 1;
  return values.map((v, i) => [(i / (values.length - 1)) * w, h - 2 - ((v - lo) / span) * (h - 4)].map(n => +n.toFixed(1)));
}
const spark = values => `<svg class="sparkline-svg" viewBox="0 0 70 20" aria-hidden="true"><path d="M${pts(values, 70, 20).join(' L')}" fill="none" stroke="${values.at(-1) >= values[0] ? UP : DOWN}" stroke-width="2"/></svg>`;
function chart(values) {
  const p = pts(values, 300, 70), up = values.at(-1) >= values[0], line = `M${p.join(' L')}`;
  return `<svg class="order-chart-svg" viewBox="0 0 300 70" preserveAspectRatio="none" aria-label="30-day price trend" role="img">
    <path d="${line} L300,70 L0,70 Z" fill="${up ? 'rgba(52, 211, 153, 0.15)' : 'rgba(248, 113, 113, 0.15)'}"/><path d="${line}" fill="none" stroke="${up ? UP : DOWN}" stroke-width="3"/></svg>`;
}

export class TradingPanel {
  constructor(game) {
    this.game = game;
    this.title = 'Summit Practice Trading Desk';
    this.tab = 'market';
    this.sel = 'SAGAR50'; this.side = 'buy'; this.qty = 1; this.move = 1000;
    this.confirm = null; this.msg = null;
  }
  get s() { return this.game.state; }

  frame() {
    const p = portfolio(this.s);
    const tab = (t, l) => `<button class="pixel-tab-btn ${this.tab === t ? 'active' : ''}" data-a="tab" data-t="${t}">${l}</button>`;
    const kpi = (l, v, c = '', id = '') => `<div class="kpi-card"><span class="kpi-label">${l}</span><span class="kpi-value ${c}"${id ? ` data-testid="${id}"` : ''}>${v}</span></div>`;
    return `<div class="vq-desk"><main class="desk-modal-wrapper">
      <section class="pixel-desk-modal" role="dialog" aria-modal="true" aria-labelledby="deskTitle">
        <header class="desk-header">
          <div class="header-branding"><div class="desk-title-row"><span class="pixel-bullet-gold">◆</span><h1 class="desk-title" id="deskTitle">${esc(this.title)}</h1></div>
            <p class="desk-subtitle">Simulated market for learning — fictional assets, not real or live prices</p></div>
          <div class="header-nav-group"><nav class="desk-tabs-bar" aria-label="Trading Desk Views">${tab('market', 'Market')}${tab('portfolio', 'Portfolio')}${tab('history', 'History')}${tab('learn', 'Risk guide')}</nav>
            <button class="pixel-btn-close" data-a="close" title="Close" aria-label="Close Trading Desk">✖</button></div>
        </header>
        <div class="simulation-notice-bar"><span class="pixel-badge-warn">SIMULATION</span>
          <p class="simulation-notice-text">Educational practice market. Prices are generated by the game and change as in-game days pass. No real trades, money or brokers. <b data-testid="desk-date">Prices as of ${fmtDate(this.s.day)}.</b></p></div>
        <section class="kpi-metrics-row" aria-label="Portfolio Metrics Summary">
          ${kpi('INVESTMENT CASH', inr(p.cash), '', 'kpi-cash')}${kpi('HOLDINGS VALUE', inr(p.invested), '', 'kpi-holdings')}${kpi('PORTFOLIO TOTAL', inr(p.total), '', 'kpi-total')}
          ${kpi('UNREALISED P/L', inr(p.unrealized), cls(p.unrealized), 'kpi-unrealised')}${kpi('REALISED P/L', inr(p.realized), cls(p.realized), 'kpi-realised')}</section>
        <section class="desk-views-viewport" data-scroll="views"><div class="tab-view active" data-testid="desk-view" data-view="${this.tab}">${this[`render_${this.tab}`](p)}</div></section>
        ${this.renderConfirm()}
      </section></main></div>`;
  }

  render_market() {
    const s = this.s, rows = Object.entries(ASSETS).map(([id, a]) => {
      const px = price(s, id), d1 = px / price(s, id, Math.max(0, s.day - 1)) - 1, d30 = px / price(s, id, Math.max(0, s.day - 30)) - 1;
      return `<div class="asset-row ${this.sel === id ? 'active' : ''}" data-a="pick" data-id="${id}" data-testid="asset-row">
        <div class="col-asset"><strong class="asset-title">${esc(a.name)}</strong><span class="asset-meta">${id} · ${esc(a.type)} · risk ${esc(a.risk)}</span></div>
        <div class="col-price" data-testid="asset-price">${inr(px)}</div><div class="col-change-1d ${cls(d1)}">${pct(d1)}</div><div class="col-change-30d ${cls(d30)}">${pct(d30)}</div>
        <div class="col-trend">${spark(history(s, id, 30))}</div><div class="col-action"><button class="pixel-btn-action-small" tabindex="-1">Trade</button></div></div>`;
    }).join('');
    return `<div class="market-split-grid">
      <div class="market-assets-pane">
        <div class="assets-table-header"><span class="col-asset">Asset (simulated)</span><span class="col-price">Price</span><span class="col-change-1d">1 day</span><span class="col-change-30d">30 days</span><span class="col-trend">30-day trend</span><span class="col-action"></span></div>
        <div class="assets-rows-list" data-scroll="assets">${rows}</div>
        ${this.bulletin()}
      </div>
      <div class="market-order-pane" data-scroll="order">${this.renderTicket()}${this.renderTransfer()}</div></div>`;
  }

  // The latest monthly newspaper issue (fixed facts; AI wording only if it was stored and validated)
  // and the market rules in force. Nothing here can change a price or a balance.
  bulletin() {
    const i = this.s.newspaper?.issues?.at(-1), A = i?.aiStatus === 'done' ? i.ai : null, d = i ? renderIssue(i) : null;
    const news = i ? `<p class="bulletin-line" data-testid="desk-news" data-issue="${i.id}"><span class="pixel-badge-warn">${A ? 'AI WORDING · CHECKED' : 'SIMULATION DATA'}</span>
        <b>${esc(monthName(i.month))} edition</b> <span>(published ${fmtShortDate(i.day)}):</span> <span>${esc(A?.headline ?? d.headline)}</span> — <span>${esc(A?.lead ?? d.lead)}</span> <span class="muted">Full issue: News (N).</span></p>`
      : '<p class="bulletin-line" data-testid="desk-news">No market newspaper yet — the first edition comes out on the 1st of next month.</p>';
    return `<div class="desk-bulletin" data-testid="desk-bulletin">${news}
      <p class="bulletin-line" data-testid="desk-params"><span class="pixel-badge-warn">ACTIVE</span> Since the start of this save: ${inr(TRADE_FEE)} fee per trade; prices follow the game's fixed random walk plus recorded simulated events.
        <span class="muted">${ACTIVATION_ENABLED ? '' : 'Proposed changes: none in force — AI parameter proposals are switched off in this version.'}</span></p></div>`;
  }

  renderTicket() {
    const s = this.s, a = ASSETS[this.sel], q = quoteTrade(s, this.sel, this.side, this.qty);
    const held = s.brokerage.holdings[this.sel]?.qty ?? 0, h = history(s, this.sel, 30), px = price(s, this.sel), d30 = px / h[0] - 1;
    const feedback = this.msg ? `<span class="${this.msg.kind === 'ok' ? 'text-pos' : ''}">${esc(this.msg.text)}</span>`
      : q.ok ? `<span class="order-estimate">Estimated ${this.side === 'buy' ? 'cost' : 'proceeds'}: <b>${inr(q.net)}</b> (incl. ${inr(TRADE_FEE)} fee)</span>` : esc(why(q));
    return `<div class="order-box-card" data-testid="order-box">
      <div class="order-header-row"><div class="order-title-block"><h3 class="order-asset-title">${esc(a.name)}</h3><span class="ticker-pill">${this.sel}</span></div>
        <div class="live-price-badge" title="Price on ${fmtDate(s.day)} (in-game)"><span class="live-price-val">${inr(px)}</span><span class="live-price-change ${cls(d30)}">${pct(d30)}</span></div></div>
      <p class="order-asset-desc">${esc(a.about)}</p>
      <div class="order-realtime-chart-box"><div class="chart-stats-row"><span class="chart-stat-item">30D HIGH: <strong>${inr(Math.max(...h))}</strong></span><span class="chart-stat-item">30D LOW: <strong>${inr(Math.min(...h))}</strong></span><span class="chart-stat-item">RISK: <strong>${esc(a.risk.toUpperCase())}</strong></span></div>
        <div class="realtime-svg-wrapper">${chart(h)}</div></div>
      <div class="order-action-toggle-row"><div class="toggle-buttons-group"><button class="pixel-toggle-btn ${this.side === 'buy' ? 'active' : ''}" data-a="side" data-t="buy" aria-pressed="${this.side === 'buy'}">Buy</button><button class="pixel-toggle-btn ${this.side === 'sell' ? 'active' : ''}" data-a="side" data-t="sell" aria-pressed="${this.side === 'sell'}">Sell</button></div>
        <span class="holding-status-text">You hold ${held}</span></div>
      <div class="order-input-row"><label for="deskQty" class="order-input-label">Quantity</label><input type="number" id="deskQty" class="pixel-input-box" min="1" step="1" value="${this.qty}" data-in="qty"></div>
      <div class="order-feedback-msg" data-testid="desk-msg" aria-live="polite">${feedback}</div>
      <button class="pixel-btn-primary-desk" data-a="review" ${q.ok && !this.confirm ? '' : 'disabled'}>Review ${this.side}</button></div>`;
  }

  renderTransfer() {
    return `<div class="transfer-box-card"><div class="transfer-header-row"><strong class="transfer-heading">Move money</strong>
        <span class="transfer-balances">Wallet ${inr(balance(this.s))} ⇄ Investment cash ${inr(balance(this.s, 'brokerage'))}</span></div>
      <div class="transfer-actions-row"><div class="transfer-input-frame"><input type="number" class="pixel-input-box" min="1" step="100" value="${this.move}" data-in="move" aria-label="Amount to move"></div>
        <button class="pixel-btn-secondary-desk" data-a="deposit">Wallet → Invest</button><button class="pixel-btn-secondary-desk" data-a="withdraw">Invest → Wallet</button></div></div>`;
  }

  renderConfirm() {
    if (!this.confirm) return '';
    const a = ASSETS[this.sel], q = quoteTrade(this.s, this.sel, this.side, this.qty);
    if (!q.ok) return '';
    return `<div class="desk-confirm" role="alertdialog" aria-label="Confirm ${this.side}"><div class="desk-confirm-card confirm"><h4>Confirm ${this.side}</h4>
      <p>${this.side === 'buy' ? 'Buy' : 'Sell'} <b>${this.qty}</b> × ${esc(a.name)} at ${inr(q.price)} (price on ${fmtShortDate(this.s.day)})<br>Value ${inr(q.gross)} ${this.side === 'buy' ? '+' : '−'} ${inr(TRADE_FEE)} fee = <b>${inr(q.net)}</b> ${this.side === 'buy' ? 'paid from' : 'added to'} investment cash.</p>
      <div class="row"><button class="pixel-btn-primary-desk" data-a="trade-confirm">Confirm</button><button class="pixel-btn-secondary-desk" data-a="cancel">Cancel</button></div></div></div>`;
  }

  empty(icon, head, sub) {
    return `<div class="empty-state-canvas"><div class="empty-dashed-box"><span class="pixel-empty-icon" aria-hidden="true">${icon}</span><p class="empty-state-headline">${head}</p><p class="empty-state-subtext">${sub}</p></div></div>`;
  }

  render_portfolio(p) {
    if (!p.rows.length) return this.empty('📂', 'No holdings yet.', 'Move money into investment cash, then buy from the Market tab.');
    const rows = p.rows.map(r => `<tr><td><b>${esc(ASSETS[r.id].name)}</b><div class="muted">${r.id}</div></td><td class="n">${r.qty}</td>
      <td class="n">${inr(r.cost / r.qty)}</td><td class="n">${inr(r.price)}</td><td class="n">${inr(r.cost)}</td><td class="n">${inr(r.value)}</td>
      <td class="n ${cls(r.pnl)}">${inr(r.pnl)} (${pct(r.pnlPct)})</td><td class="n">${p.invested ? Math.round(r.value / p.invested * 100) : 0}%</td></tr>`).join('');
    const top = Math.max(...p.rows.map(r => r.value)) / (p.invested || 1);
    return `<div class="desk-sheet" data-scroll="sheet"><table class="t"><tr><th>Asset</th><th class="n">Units</th><th class="n">Avg cost</th><th class="n">Price</th><th class="n">Cost basis</th><th class="n">Value</th><th class="n">P/L</th><th class="n">Weight</th></tr>${rows}</table>
      <p class="pixel-disclaimer-p">Diversification: ${p.rows.length} holding(s); largest is ${Math.round(top * 100)}% of your investments.
      ${top > 0.6 ? 'Most of your money rides on one asset — a single bad event would hurt a lot.' : 'No single asset dominates.'}</p>
      <p class="muted">Cost basis includes the ${inr(TRADE_FEE)} fee per buy. Selling uses the average-cost method. Values at ${fmtDate(this.s.day)} prices.</p></div>`;
  }

  render_history() {
    const t = [...this.s.brokerage.trades].reverse();
    if (!t.length) return this.empty('📜', 'No trades yet.', 'Past buy and sell transactions will be recorded here chronologically.');
    return `<div class="desk-sheet" data-scroll="sheet"><table class="t"><tr><th>Date</th><th>Trade</th><th class="n">Price</th><th class="n">Fee</th><th class="n">Cash</th><th class="n">Realised P/L</th></tr>${t.map(x => `
      <tr><td>${fmtShortDate(x.day)}</td><td>${x.side === 'buy' ? 'Buy' : 'Sell'} ${x.qty} ${x.asset}</td><td class="n">${inr(x.price)}</td><td class="n">${inr(x.fee)}</td>
      <td class="n ${x.side === 'buy' ? 'text-neg' : 'text-pos'}">${x.side === 'buy' ? '−' : '+'}${inr(x.net)}</td><td class="n ${cls(x.realized ?? 0)}">${x.realized === null ? '—' : inr(x.realized)}</td></tr>`).join('')}</table></div>`;
  }

  // The design's four disclaimer cards, filled with the game's own risk guide.
  render_learn() {
    const card = (t, b) => `<p class="pixel-disclaimer-p"><strong>${t}</strong><br>${b}</p>`;
    return `<div class="risk-guide-canvas"><div class="risk-disclaimer-card"><div class="risk-disclaimer-header"><span class="pixel-bullet-red">◆</span><h2 class="risk-heading">Educational risk guide</h2></div>
      <div class="risk-text-scrollbox" data-scroll="risk">
        ${card('1. Risk', 'Risk is how much an investment\'s value can swing — including below what you paid. Each asset here is labelled Low → Very high. Higher expected returns usually come with bigger swings.')}
        ${card('2. Diversification', 'Spreading money across different assets means one bad event can\'t wreck your portfolio. The Sagar 50 index fund is diversified by itself; adding the bond fund spreads risk further.')}
        ${card('3. Time horizon', 'Money you need soon (tuition, rent, emergencies) shouldn\'t be in volatile assets. Keep an emergency fund in your wallet first.')}
        ${card('4. Fees', `Fees (${inr(TRADE_FEE)} per trade here) add up when you trade often.`)}
        ${card('5. Simulation', 'All prices are generated by the simulation from your save\'s in-game date. Nothing here is real or live market data, and nothing here is financial advice.')}
      </div></div></div>`;
  }

  onInput(el) {
    if (el.dataset.in === 'qty') { this.qty = Math.max(1, Math.floor(Number(el.value) || 1)); this.confirm = null; }
    if (el.dataset.in === 'move') this.move = Math.max(0, Math.floor(Number(el.value) || 0));
  }

  onAction(a, el) {
    this.msg = a === 'tab' ? this.msg : null;
    switch (a) {
      case 'tab': this.tab = el.dataset.t; this.confirm = null; break;
      case 'pick': this.sel = el.dataset.id; this.confirm = null; break;
      case 'side': this.side = el.dataset.t; this.confirm = null; break;
      case 'review': this.confirm = { token: newToken() }; break;
      case 'cancel': this.confirm = null; break;
      case 'trade-confirm': {
        const token = this.confirm?.token; this.confirm = null;
        const r = this.game.act(s => trade(s, this.sel, this.side, this.qty, token));
        this.msg = r.ok ? { kind: 'ok', text: `${r.trade.side === 'buy' ? 'Bought' : 'Sold'} ${r.trade.qty} ${r.trade.asset} at ${inr(r.trade.price)} (${inr(r.trade.net)} incl. fee).${r.trade.realized !== null ? ` Realised P/L ${inr(r.trade.realized)}.` : ''}` }
                        : { kind: 'error', text: why(r) };
        break;
      }
      case 'deposit': case 'withdraw': {
        const [from, to] = a === 'deposit' ? ['wallet', 'brokerage'] : ['brokerage', 'wallet'];
        const r = this.game.act(s => transfer(s, from, to, this.move, a === 'deposit' ? 'Wallet → investment cash' : 'Investment cash → wallet'));
        this.msg = r.ok ? { kind: 'ok', text: `Moved ${inr(this.move)}.` } : { kind: 'error', text: r.reason === 'insufficient_funds' ? `Not enough money in your ${from === 'wallet' ? 'wallet' : 'investment cash'}.` : whyBase(r) };
        break;
      }
    }
  }
}
