"""Generate src/data/achievements.js from the supplied achievement pop-up frontend
(Assets/supplied-ui/achievements/index.html, from VanQuest_Achievement_Popups_Frontend.zip).
Names, descriptions, icons, rarities, XP and groups are copied exactly; the game's eligibility rules
live in src/sim/achievements.js.   Run:  python3 tools/extract_achievements.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
html = (ROOT / "Assets" / "supplied-ui" / "achievements" / "index.html").read_text(encoding="utf-8")
block = re.search(r"const achievements = \[(.*?)\n\];", html, re.S).group(1)
rows = []
for line in block.strip().splitlines():
    obj = re.sub(r"(?<=[{,])(\w+):", r'"\1":', line.strip().rstrip(","))   # quote the keys only
    rows.append(json.loads(obj))
footer = re.search(r"<footer>(.*?)</footer>", html, re.S).group(1).strip()
out = ROOT / "src" / "data" / "achievements.js"
out.write_text(
    "// GENERATED by tools/extract_achievements.py from the supplied achievement frontend\n"
    "// (Assets/supplied-ui/achievements/index.html). Do not edit by hand.\n"
    f"export const SUPPLIED_ACHIEVEMENTS = {json.dumps(rows, ensure_ascii=False, indent=1)};\n"
    f"export const SUPPLIED_FOOTER = {json.dumps(footer, ensure_ascii=False)};\n", encoding="utf-8")
print(f"{len(rows)} achievements -> {out.relative_to(ROOT)}")
