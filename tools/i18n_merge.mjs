// Translator helper (Round 9): merge "N<TAB>Telugu" lines into a catalogue file.
//   node tools/i18n_merge.mjs <batch.txt> <translations.txt> <src/i18n/te/file.js>
// Every line is checked: the number must exist in the batch, the {n} placeholders must be exactly those of
// the English template, and the text must contain Telugu script (or be an allowed English-only label).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const [, , batchFile, trFile, target] = process.argv;
const parse = f => new Map(readFileSync(f, 'utf8').split('\n').filter(l => l.trim()).map(l => { const i = l.indexOf('\t'); return [Number(l.slice(0, i)), l.slice(i + 1)]; }));
const batch = parse(batchFile), tr = parse(trFile);
const ph = s => [...s.matchAll(/\{(\d+)\}/g)].map(m => m[1]).sort().join(',');
const cur = existsSync(target) ? (await import(new URL(`file://${process.cwd()}/${target}`).href + `?${Date.now()}`)).default : {};
let added = 0; const errors = [];
for (const [n, te] of tr) {
  const en = batch.get(n);
  if (en == null) { errors.push(`${n}: not in batch`); continue; }
  if (/^\s*(=|SAME)\s*$/.test(te)) { cur[en] = en; added++; continue; }
  if (ph(en) !== ph(te)) { errors.push(`${n}: placeholders ${ph(en)} ≠ ${ph(te)} — ${en}`); continue; }
  if (!/[ఀ-౿]/.test(te) && !/^\s*(=|SAME)\s*$/.test(te)) { errors.push(`${n}: no Telugu — ${te}`); continue; }
  cur[en] = /^\s*(=|SAME)\s*$/.test(te) ? en : te.trim(); added++;
}
const keys = Object.keys(cur).sort();
writeFileSync(target, `// GENERATED by tools/i18n_merge.mjs from reviewed translation batches — English template → Telugu.\n// Edit a value here, or add a line to a batch and re-merge. {0}, {1}… are names, dates and numbers (src/i18n/i18n.js).\nexport default {\n${keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(cur[k])},`).join('\n')}\n};\n`);
console.log(`${target}: +${added}, total ${keys.length}${errors.length ? `\n${errors.length} rejected:\n  ${errors.join('\n  ')}` : ''}`);
process.exitCode = errors.length ? 1 : 0;
